def bi(key: str, static: str | None) -> str:
    """Bilingual span pair, or a single language when --static is used."""
    es, en = T[key]
    if static == "es":
        return html.escape(es)
    if static == "en":
        return html.escape(en)
    return f'<span class="es">{html.escape(es)}</span><span class="en">{html.escape(en)}</span>'


def bi2(pair: tuple[str, str], static: str | None) -> str:
    es, en = pair
    if static == "es":
        return html.escape(es)
    if static == "en":
        return html.escape(en)
    return f'<span class="es">{html.escape(es)}</span><span class="en">{html.escape(en)}</span>'


